#!/usr/bin/env python3

import argparse
import os
import hashlib
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

def parser():
    """parse the arguments of the program"""
    parser = argparse.ArgumentParser(prog='totp')
    parser.add_argument("-g", help="encrypt a file containing an hexadecimal key of at least 64 characters")
    parser.add_argument("-k", help="generates a temporary password from ft_otp.key file generated by -g option")
    values = parser.parse_args()
    if values.g and values.k:
        print("Wrong usage only one option -g or -k, use --help or -h for more information")
        exit()
    if not values.g and not values.k:
        print("Missing options, use --help or -h for more information")
        exit()
    return values


def is_valid_hex(content: str) -> bool:#surment un truc a faire gaffe avec upper() lower()
    """check hexadecimal did not find something i like"""
    hexadecimal = "0123456789abcdef"
    for i in content:
        if i not in hexadecimal:
            return False
    if len(content) < 64:
        return False
    return True


def generate_key(file: string) -> None:
    """generate ft_otp.key with AES256"""
    try:
        fd = open(file)#la je crois je dois mettre des options
    except Exception as e:
        print(f"{type(e).__name__}: {e}")
        return
    content = fd.read()
    if not content:
        print("./ft_otp: error: no content in the file")
        exit()
    if not is_valid_hex(content):
        print("./ft_otp: error: key must be 64 hexadecimal characters.")
        exit()
    raw_key = os.getlogin()
    secret = bytes.fromhex(content)
    salt = os.urandom(16)
    nonce = os.urandom(12)
    key = hashlib.pbkdf2_hmac("sha256", raw_key.encode(), salt, 600_000, dklen=32)
    data = salt + nonce + AESGCM(key).encrypt(nonce, secret, None)
    open("ft_otp.key", "wb").write(data)


def generate_totp(file: string) -> None:
    """read ft_otp.key and generate a TOTP"""
    try:
        fd = open(file, "rb")
    except Exception as e:
        print(f"{type(e).__name__} : {e}")
        exit()
    data  = fd.read()
    salt, nonce, ct = data[:16], data[16:28], data[28:]
    key   = hashlib.pbkdf2_hmac("sha256", os.getlogin().encode(), salt, 600_000, dklen=32)
    secret = AESGCM(key).decrypt(nonce, ct, None)
    print(str(secret))


def totp() -> None:
    """program which can generate a key to generate TOTP code in a second time"""
    values = parser()
    if values.g:
        generate_key(values.g)
    elif values.k:
        generate_totp(values.k)
    

if __name__ == "__main__":
    totp()
